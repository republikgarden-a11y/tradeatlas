const assert=require('node:assert/strict');
const t=require('../translation.js');
const original={id:'a',language:'en',title:'Medical cannabis research',excerpt:'The study follows 100 patients.',url:'https://example.org/article?lang=en&x=1'};
const translated={...original,translation:{targetLanguage:'fr',sourceLanguage:'en',sourceTitle:original.title,sourceExcerpt:original.excerpt,title:'Recherche sur le cannabis médical',excerpt:'L’étude suit 100 patients.'}};
assert.equal(t.display(translated,true).title,'Recherche sur le cannabis médical');
assert.equal(t.display(translated,true).language,'fr');
assert.equal(t.display(translated,false).title,original.title);
assert.equal(t.display(translated,false).excerpt,original.excerpt);
assert.equal(t.valid({...translated,title:'Changed source title'}),false);
assert.equal(t.valid({...translated,excerpt:'Changed source excerpt'}),false);
assert.equal(t.display(original,true).unavailable,true);
assert.equal(t.display(original,true).language,'en');
assert.equal(t.display(original,true).title,original.title);
assert.equal(t.readerURL(translated,false),original.url);
assert.equal(t.readerURL(translated,true,true),original.url);
const link=new URL(t.readerURL(translated,true));
assert.equal(link.hostname,'translate.google.com');
assert.equal(link.searchParams.get('tl'),'fr');
assert.equal(link.searchParams.get('sl'),'en');
assert.equal(link.searchParams.get('u'),original.url);
assert.equal(t.readerURL({...translated,url:'javascript:alert(1)'},true),'');
const french={...original,language:'fr',title:'Article en français'};
assert.equal(t.display(french,true).title,french.title);
assert.equal(t.readerURL(french,true),original.url);
process.stdout.write('Traduction : original exact, cache invalidé, lecture française et liens vérifiés.\n');

const oldFavorite={...original,id:'old',title:'Old saved article'};
const saved=t.savedCorpus([translated],{a:original,old:oldFavorite},['a','old']);
assert.equal(saved.length,2);assert.equal(saved.find(i=>i.id==='a').translation.title,translated.translation.title);assert.equal(saved.filter(t.valid).length,1);assert.equal(saved.find(i=>i.id==='old').title,oldFavorite.title);
